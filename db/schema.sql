);

-- ---------------------------------------------------------------------
-- 5. INSUMOS, PRODUCTOS Y RECETAS
-- ---------------------------------------------------------------------

CREATE TABLE insumos (
  id_insumo                 INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_insumo >= 0),
  nombre                    CITEXT   NOT NULL,
  descripcion               VARCHAR(150) NULL,
  id_categoria              INTEGER NOT NULL,
  id_unidad_medida          INTEGER NOT NULL,
  stock_actual              DECIMAL(12,3) NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
  stock_minimo              DECIMAL(12,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  costo_unitario_referencia DECIMAL(10,2) NULL CHECK (costo_unitario_referencia IS NULL OR costo_unitario_referencia >= 0),
  activo                    BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_insumo),
  CONSTRAINT uq_insumo_nombre UNIQUE (nombre),
  CONSTRAINT fk_insumo_categoria FOREIGN KEY (id_categoria)     REFERENCES categorias_insumos (id_categoria) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_insumo_unidad    FOREIGN KEY (id_unidad_medida) REFERENCES unidades_medida (id_unidad)       ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_insumo_categoria ON insumos (id_categoria);
CREATE INDEX idx_insumo_unidad ON insumos (id_unidad_medida);
COMMENT ON TABLE insumos IS 'stock_actual es un valor cacheado; su historial detallado vive en movimientos_inventario, y debe mantenerse sincronizado desde la aplicación.';

CREATE TABLE productos (
  id_producto         INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_producto >= 0),
  nombre              CITEXT   NOT NULL,
  descripcion         VARCHAR(150) NULL,
  id_categoria        INTEGER NOT NULL,
  id_area_preparacion INTEGER NOT NULL,
  precio_actual       DECIMAL(10,2) NOT NULL CHECK (precio_actual >= 0),
  disponible          BOOLEAN NOT NULL DEFAULT TRUE,
  activo              BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_producto),
  CONSTRAINT uq_producto_nombre UNIQUE (nombre),
  CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria)        REFERENCES categorias_productos (id_categoria) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_producto_area      FOREIGN KEY (id_area_preparacion) REFERENCES areas_preparacion (id_area)         ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_producto_categoria ON productos (id_categoria);
COMMENT ON COLUMN productos.disponible IS 'Disponibilidad momentánea (86 / se acabó hoy)';
COMMENT ON COLUMN productos.activo IS 'Baja lógica permanente del catálogo';

CREATE TABLE recetas (
  id_receta      INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_receta >= 0),
  id_producto    INTEGER NOT NULL,
  id_insumo      INTEGER NOT NULL,
  cantidad_usada DECIMAL(10,3) NOT NULL CHECK (cantidad_usada > 0),
  PRIMARY KEY (id_receta),
  CONSTRAINT uq_receta_producto_insumo UNIQUE (id_producto, id_insumo),
  CONSTRAINT fk_receta_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_receta_insumo   FOREIGN KEY (id_insumo)   REFERENCES insumos (id_insumo)     ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_receta_insumo ON recetas (id_insumo);
COMMENT ON COLUMN recetas.cantidad_usada IS 'En la unidad de medida del insumo referenciado';

-- ---------------------------------------------------------------------
-- 6. COMPRAS
-- ---------------------------------------------------------------------

CREATE TABLE compras (
  id_compra    INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_compra >= 0),
  id_proveedor INTEGER NOT NULL,
  id_empleado  INTEGER NOT NULL,
  fecha_compra TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  total        DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  PRIMARY KEY (id_compra),
  CONSTRAINT fk_compra_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedores (id_proveedor) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_compra_empleado  FOREIGN KEY (id_empleado)  REFERENCES empleados (id_empleado)    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_compra_proveedor ON compras (id_proveedor);
CREATE INDEX idx_compra_empleado ON compras (id_empleado);
CREATE INDEX idx_compra_fecha ON compras (fecha_compra);
COMMENT ON COLUMN compras.id_empleado IS 'Quién registró la compra';
COMMENT ON COLUMN compras.total IS 'Debe igualar a SUM(detalle_compra.subtotal); mantenido por la aplicación';

CREATE TABLE detalle_compra (
  id_detalle_compra INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_detalle_compra >= 0),
  id_compra         INTEGER NOT NULL,
  id_insumo         INTEGER NOT NULL,
  cantidad          DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario    DECIMAL(10,2) NOT NULL CHECK (costo_unitario >= 0),
  subtotal          DECIMAL(12,2) GENERATED ALWAYS AS (cantidad * costo_unitario) STORED,
  PRIMARY KEY (id_detalle_compra),
  CONSTRAINT fk_detcompra_compra FOREIGN KEY (id_compra) REFERENCES compras (id_compra) ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_detcompra_insumo FOREIGN KEY (id_insumo) REFERENCES insumos (id_insumo) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_detcompra_compra ON detalle_compra (id_compra);
CREATE INDEX idx_detcompra_insumo ON detalle_compra (id_insumo);
COMMENT ON TABLE detalle_compra IS 'subtotal es columna generada (cantidad*costo_unitario): elimina la redundancia/anomalía de actualización que existía en el dump original.';

-- ---------------------------------------------------------------------
-- 7. MESAS, ÓRDENES, DETALLES Y PAGOS
-- ---------------------------------------------------------------------

CREATE TABLE mesas (
  id_mesa     INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_mesa >= 0),
  numero_mesa INTEGER NOT NULL CHECK (numero_mesa >= 0),
  capacidad   INTEGER NOT NULL CHECK (capacidad > 0),
  estado      CITEXT NOT NULL DEFAULT 'Disponible' CHECK (estado IN ('Disponible','Ocupada')),
  PRIMARY KEY (id_mesa),
  CONSTRAINT uq_mesa_numero UNIQUE (numero_mesa)
);

CREATE TABLE ordenes (
  id_orden              INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_orden >= 0),
  id_tipo_orden         INTEGER NOT NULL,
  id_mesa               INTEGER NULL,
  id_cliente            INTEGER NULL,
  id_empleado_atiende   INTEGER NULL,
  id_usuario_registro   INTEGER NOT NULL,
  id_plataforma_externa INTEGER NULL,
  referencia_externa    VARCHAR(50) NULL,
  fecha_orden           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  numero_orden_diaria   INTEGER NOT NULL CHECK (numero_orden_diaria > 0),
  id_estado             INTEGER NOT NULL,
  total                 DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  creado_en             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_orden),
  CONSTRAINT fk_orden_tipo       FOREIGN KEY (id_tipo_orden)         REFERENCES tipos_orden (id_tipo_orden)          ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_orden_mesa       FOREIGN KEY (id_mesa)               REFERENCES mesas (id_mesa)                      ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_orden_cliente    FOREIGN KEY (id_cliente)            REFERENCES clientes (id_cliente)                ON DELETE SET NULL  ON UPDATE CASCADE,
  CONSTRAINT fk_orden_empleado   FOREIGN KEY (id_empleado_atiende)   REFERENCES empleados (id_empleado)              ON DELETE SET NULL  ON UPDATE CASCADE,
  CONSTRAINT fk_orden_usuario    FOREIGN KEY (id_usuario_registro)   REFERENCES usuarios (id_usuario)                ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_orden_plataforma FOREIGN KEY (id_plataforma_externa) REFERENCES plataformas_externas (id_plataforma) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_orden_estado     FOREIGN KEY (id_estado)             REFERENCES estados_orden (id_estado)            ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_orden_mesa ON ordenes (id_mesa);
CREATE INDEX idx_orden_cliente ON ordenes (id_cliente);
CREATE INDEX idx_orden_empleado ON ordenes (id_empleado_atiende);
CREATE INDEX idx_orden_estado ON ordenes (id_estado);
CREATE INDEX idx_orden_fecha ON ordenes (fecha_orden);
CREATE INDEX idx_orden_tipo ON ordenes (id_tipo_orden);
CREATE UNIQUE INDEX uq_orden_numero_diaria ON ordenes (DATE(fecha_orden), numero_orden_diaria);
COMMENT ON COLUMN ordenes.id_mesa IS 'Obligatoria solo cuando tipos_orden.requiere_mesa = TRUE (validado por la app)';
COMMENT ON COLUMN ordenes.numero_orden_diaria IS 'Consecutivo visible de la orden dentro de su día; reinicia a 1 cada día';
COMMENT ON COLUMN ordenes.id_empleado_atiende IS 'Mesero/repartidor asignado';
COMMENT ON COLUMN ordenes.id_usuario_registro IS 'Usuario del sistema que capturó la orden (auditoría)';
COMMENT ON COLUMN ordenes.id_plataforma_externa IS 'Obligatoria solo cuando tipos_orden.requiere_plataforma = TRUE';
COMMENT ON COLUMN ordenes.referencia_externa IS 'Número de pedido en Rappi/Uber Eats/DiDi Food, si aplica';
COMMENT ON COLUMN ordenes.total IS 'Debe igualar a SUM(detalles_orden.subtotal); mantenido por la aplicación';

CREATE TABLE detalles_orden (
  id_detalle          INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_detalle >= 0),
  id_orden            INTEGER NOT NULL,
  id_producto         INTEGER NOT NULL,
  cantidad            INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario     DECIMAL(10,2) NOT NULL CHECK (precio_unitario >= 0),
  subtotal            DECIMAL(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
  id_area_preparacion INTEGER NOT NULL,
  id_estado           INTEGER NOT NULL,
  PRIMARY KEY (id_detalle),
  CONSTRAINT fk_detorden_orden    FOREIGN KEY (id_orden)            REFERENCES ordenes (id_orden)                ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_detorden_producto FOREIGN KEY (id_producto)         REFERENCES productos (id_producto)           ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_detorden_area     FOREIGN KEY (id_area_preparacion) REFERENCES areas_preparacion (id_area)       ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_detorden_estado   FOREIGN KEY (id_estado)           REFERENCES estados_detalle_orden (id_estado) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_detorden_orden ON detalles_orden (id_orden);
CREATE INDEX idx_detorden_producto ON detalles_orden (id_producto);
CREATE INDEX idx_detorden_estado ON detalles_orden (id_estado);
COMMENT ON COLUMN detalles_orden.precio_unitario IS 'Precio histórico al momento de la venta (no se actualiza si cambia productos.precio_actual)';
COMMENT ON COLUMN detalles_orden.id_area_preparacion IS 'Copiado de productos.id_area_preparacion al capturar la orden';

CREATE TABLE pagos (
  id_pago             INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_pago >= 0),
  id_orden            INTEGER NOT NULL,
  id_metodo_pago      INTEGER NOT NULL,
  monto               DECIMAL(10,2) NOT NULL CHECK (monto > 0),
  fecha_pago          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  referencia_pago     VARCHAR(100) NULL,
  id_usuario_registro INTEGER NOT NULL,
  PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_orden   FOREIGN KEY (id_orden)            REFERENCES ordenes (id_orden)            ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_pago_metodo  FOREIGN KEY (id_metodo_pago)      REFERENCES metodos_pago (id_metodo_pago) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_pago_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuarios (id_usuario)         ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_pago_orden ON pagos (id_orden);
CREATE INDEX idx_pago_metodo ON pagos (id_metodo_pago);
COMMENT ON TABLE pagos IS 'Una orden puede tener varios pagos (cuenta dividida): no existe UNIQUE sobre id_orden.';

CREATE TABLE tickets (
  id_ticket        INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_ticket >= 0),
  id_orden         INTEGER NOT NULL,
  folio            CITEXT NOT NULL,
  tipo             CITEXT NOT NULL DEFAULT 'Cuenta' CHECK (tipo IN ('Cuenta','Comanda_Cocina','Comanda_Bar','Reimpresion')),
  id_usuario_emite INTEGER NOT NULL,
  fecha_emision    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_ticket),
  CONSTRAINT uq_ticket_folio UNIQUE (folio),
  CONSTRAINT fk_ticket_orden   FOREIGN KEY (id_orden)         REFERENCES ordenes (id_orden)   ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_ticket_usuario FOREIGN KEY (id_usuario_emite) REFERENCES usuarios (id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_ticket_orden ON tickets (id_orden);

