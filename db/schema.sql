-- Catálogo de personalizaciones permitidas por producto. El precio extra se
-- suma al precio de la partida; el inventario se ajusta con la foto histórica
-- guardada en detalle_modificadores, no con este catálogo vigente.
CREATE TABLE modificadores_producto (
  id_modificador  INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_modificador >= 0),
  id_producto     INTEGER NOT NULL,
  tipo            VARCHAR(10) NOT NULL CHECK (tipo IN ('Quitar','Extra','Sustituir')),
  nombre          CITEXT NOT NULL,
  id_insumo       INTEGER NOT NULL,
  id_insumo_nuevo INTEGER NULL,
  cantidad        DECIMAL(10,3) NULL CHECK (cantidad IS NULL OR cantidad > 0),
  precio_extra    DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (precio_extra >= 0),
  activo          BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_modificador),
  CONSTRAINT uq_modificador_producto_nombre UNIQUE (id_producto, nombre),
  CONSTRAINT fk_modificador_producto FOREIGN KEY (id_producto)     REFERENCES productos (id_producto) ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_modificador_insumo   FOREIGN KEY (id_insumo)       REFERENCES insumos (id_insumo)     ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_modificador_nuevo    FOREIGN KEY (id_insumo_nuevo) REFERENCES insumos (id_insumo)     ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_modificador_tipo CHECK (
    (tipo = 'Quitar'
      AND id_insumo_nuevo IS NULL
      AND cantidad IS NULL)
    OR (tipo = 'Extra'
      AND id_insumo_nuevo IS NULL
      AND cantidad IS NOT NULL)
    OR (tipo = 'Sustituir'
      AND id_insumo_nuevo IS NOT NULL
      AND id_insumo_nuevo <> id_insumo
      AND cantidad IS NOT NULL)
  )
);
CREATE INDEX idx_modificador_producto ON modificadores_producto (id_producto);
CREATE INDEX idx_modificador_insumo ON modificadores_producto (id_insumo);
COMMENT ON TABLE modificadores_producto IS 'Quitar omite un insumo de la receta; Extra suma un insumo; Sustituir omite id_insumo y suma id_insumo_nuevo.';
COMMENT ON COLUMN modificadores_producto.cantidad IS 'Cantidad del insumo que se suma en Extra y Sustituir; NULL en Quitar.';

