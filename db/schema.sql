-- ---------------------------------------------------------------------
-- 8.1 MERMAS Y PÉRDIDAS DE INVENTARIO
-- ---------------------------------------------------------------------
-- Diseño: `mermas` documenta el incidente (tipo de pérdida, responsable,
-- costo estimado, si se reportó a una autoridad). Una merma puede estar
-- PENDIENTE con `id_movimiento = NULL` y sus datos de insumo/cantidad en
-- `auditoria` (tabla_afectada = 'mermas_pendientes'). Al confirmarla:
--   - si es una partida ya vendida, solo se registra el costo (la venta ya
--     descontó stock);
--   - si es una captura manual, se crea el movimiento tipo 'Merma' y se
--     descuenta el inventario en ese momento.
-- El movimiento y la actualización de stock se hacen juntos en la misma
-- transacción desde el backend.

CREATE TABLE tipos_merma (
  id_tipo_merma INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_tipo_merma >= 0),
  nombre        CITEXT   NOT NULL,
  requiere_reporte_autoridad BOOLEAN NOT NULL DEFAULT FALSE,
  descripcion   VARCHAR(150) NULL,
  PRIMARY KEY (id_tipo_merma),
  CONSTRAINT uq_tipomerma_nombre UNIQUE (nombre)
);
COMMENT ON COLUMN tipos_merma.nombre IS 'Caducidad, Merma de cocina, Accidente, Robo, Otro';
COMMENT ON COLUMN tipos_merma.requiere_reporte_autoridad IS 'Sugerido TRUE para Robo';

CREATE TABLE mermas (
  id_merma                INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_merma >= 0),
  id_movimiento           INTEGER NULL,
  id_tipo_merma           INTEGER NOT NULL,
  id_empleado_responsable INTEGER NULL,
  id_usuario_registro     INTEGER NOT NULL,
  descripcion             VARCHAR(255) NOT NULL,
  costo_estimado_perdida  DECIMAL(12,2) NULL CHECK (costo_estimado_perdida IS NULL OR costo_estimado_perdida >= 0),
  reportado_autoridad     BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_deteccion         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_merma),
  CONSTRAINT uq_merma_movimiento UNIQUE (id_movimiento),
  CONSTRAINT fk_merma_movimiento FOREIGN KEY (id_movimiento)           REFERENCES movimientos_inventario (id_movimiento) ON DELETE CASCADE  ON UPDATE CASCADE,
  CONSTRAINT fk_merma_tipo       FOREIGN KEY (id_tipo_merma)           REFERENCES tipos_merma (id_tipo_merma)            ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_merma_empleado   FOREIGN KEY (id_empleado_responsable) REFERENCES empleados (id_empleado)                ON DELETE SET NULL  ON UPDATE CASCADE,
  CONSTRAINT fk_merma_usuario    FOREIGN KEY (id_usuario_registro)     REFERENCES usuarios (id_usuario)                  ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_merma_tipo ON mermas (id_tipo_merma);
CREATE INDEX idx_merma_empleado ON mermas (id_empleado_responsable);
CREATE INDEX idx_merma_usuario ON mermas (id_usuario_registro);
COMMENT ON COLUMN mermas.id_movimiento IS 'Movimiento de salida al confirmar; NULL mientras la merma está pendiente o si corresponde a una partida ya vendida';
COMMENT ON COLUMN mermas.id_empleado_responsable IS 'Empleado que causó/detectó la pérdida; puede diferir de quien la captura';
COMMENT ON COLUMN mermas.id_usuario_registro IS 'Usuario del sistema que documentó el reporte';
COMMENT ON COLUMN mermas.descripcion IS 'Detalle específico del incidente';
COMMENT ON COLUMN mermas.fecha_deteccion IS 'Puede diferir de fecha_movimiento si se detecta/reporta después';
COMMENT ON TABLE mermas IS 'Detalle de mermas/pérdidas. Pendiente: id_movimiento NULL y datos en auditoria (mermas_pendientes). Confirmada manual: movimiento Merma. Partida vendida: solo costo.';

-- ---------------------------------------------------------------------
-- 9. AUDITORÍA
-- ---------------------------------------------------------------------

CREATE TABLE auditoria (
  id_auditoria         BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_auditoria >= 0),
  id_usuario           INTEGER NULL,
  tabla_afectada       CITEXT NOT NULL,
  id_registro_afectado INTEGER NOT NULL CHECK (id_registro_afectado >= 0),
  accion               CITEXT NOT NULL CHECK (accion IN ('INSERT','UPDATE','DELETE')),
  datos_anteriores     JSONB NULL,
  datos_nuevos         JSONB NULL,
  fecha                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_auditoria),
  CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX idx_auditoria_usuario ON auditoria (id_usuario);
CREATE INDEX idx_auditoria_tabla ON auditoria (tabla_afectada, id_registro_afectado);
CREATE INDEX idx_auditoria_fecha ON auditoria (fecha);
COMMENT ON COLUMN auditoria.id_usuario IS 'NULL para acciones automáticas del sistema';
COMMENT ON TABLE auditoria IS 'Bitácora genérica; puede alimentarse desde la aplicación o desde triggers si más adelante se requiere.';
