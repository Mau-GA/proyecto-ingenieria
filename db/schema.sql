-- Configuración de los semáforos de tiempo del KDS (Comandas). Es una tabla
-- de una sola fila: el CHECK del id impide crear configuraciones paralelas.
CREATE TABLE configuracion_kds (
  id_configuracion      INTEGER NOT NULL DEFAULT 1 CHECK (id_configuracion = 1),
  umbral_amarillo_min   INTEGER NOT NULL CHECK (umbral_amarillo_min > 0),
  umbral_rojo_min       INTEGER NOT NULL CHECK (umbral_rojo_min > umbral_amarillo_min),
  PRIMARY KEY (id_configuracion)
);
COMMENT ON TABLE configuracion_kds IS 'Umbrales en minutos para el color de las tarjetas de Comandas';
COMMENT ON COLUMN configuracion_kds.umbral_amarillo_min IS 'A partir de este tiempo la tarjeta se muestra amarilla';
COMMENT ON COLUMN configuracion_kds.umbral_rojo_min IS 'A partir de este tiempo la tarjeta se muestra roja; debe ser mayor que el amarillo';

