-- =====================================================================
-- proyectorestaurante — SCHEMA NORMALIZADO (3FN)
-- Motor: PostgreSQL 16 | Charset: UTF8 | Texto comparable: citext
-- =====================================================================
-- Convenciones:
--   * Todas las tablas usan transacciones + integridad referencial.
--   * Montos monetarios -> DECIMAL(10,2). Cantidades de insumo -> DECIMAL(12,3)
--     (se admiten fracciones de kg/litro con precisión de gramo/mililitro).
--   * Catálogos controlados en vez de VARCHAR libres, para: roles/permisos,
--     puestos, unidades de medida, métodos de pago, estados de orden/detalle,
--     tipos de orden, plataformas externas, tipos de movimiento de inventario
--     y áreas de preparación. Los ENUM de MariaDB se traducen a CITEXT + CHECK
--     (mismo conjunto de valores y comparación sin distinguir mayúsculas).
--   * Las columnas de texto que se comparan con = o tienen UNIQUE usan CITEXT
--     para comparar sin distinguir mayúsculas/minúsculas.
--   * La lógica de negocio (descuento de inventario en ventas, cálculo de
--     totales, validaciones cruzadas tipo_orden/mesa, etc.) se implementa en
--     la capa de aplicación, no con triggers, para mantener el modelo
--     simple, testeable y depurable desde el backend.
-- =====================================================================

-- Extensión para comparar/almacenar texto sin distinguir mayúsculas.
CREATE EXTENSION IF NOT EXISTS citext;

-- ---------------------------------------------------------------------
-- 1. CATÁLOGOS DE SEGURIDAD: ROLES Y PERMISOS
-- ---------------------------------------------------------------------

CREATE TABLE roles (
  id_rol        INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_rol >= 0),
  nombre        CITEXT   NOT NULL,
  descripcion   VARCHAR(150) NULL,
  activo        BOOLEAN  NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_rol),
  CONSTRAINT uq_roles_nombre UNIQUE (nombre)
);

CREATE TABLE permisos (
  id_permiso    INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_permiso >= 0),
  clave         CITEXT   NOT NULL,
  descripcion   VARCHAR(150) NULL,
  PRIMARY KEY (id_permiso),
  CONSTRAINT uq_permisos_clave UNIQUE (clave)
);
COMMENT ON COLUMN permisos.clave IS 'Identificador único usado por el backend, ej. ordenes.crear';

CREATE TABLE roles_permisos (
  id_rol      INTEGER NOT NULL,
  id_permiso  INTEGER NOT NULL,
  PRIMARY KEY (id_rol, id_permiso),
  CONSTRAINT fk_rp_rol     FOREIGN KEY (id_rol)     REFERENCES roles (id_rol)         ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_rp_permiso FOREIGN KEY (id_permiso) REFERENCES permisos (id_permiso)  ON DELETE CASCADE ON UPDATE CASCADE
);

