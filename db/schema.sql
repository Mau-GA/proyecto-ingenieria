CREATE TABLE motivos_cancelacion (
  id      INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id >= 0),
  nombre  CITEXT NOT NULL,
  activo  BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id),
  CONSTRAINT uq_motivo_cancelacion_nombre UNIQUE (nombre)
);

CREATE TABLE cancelaciones (
  id                   INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id >= 0),
  id_orden             INTEGER NOT NULL,
  id_motivo            INTEGER NOT NULL,
  comentario           VARCHAR(200) NULL,
  id_usuario_solicita  INTEGER NOT NULL,
  id_usuario_autoriza  INTEGER NOT NULL,
  fecha                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_cancelacion_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT uq_cancelacion_orden_unica UNIQUE (id_orden),
  CONSTRAINT fk_cancelacion_motivo FOREIGN KEY (id_motivo) REFERENCES motivos_cancelacion (id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_cancelacion_solicita FOREIGN KEY (id_usuario_solicita) REFERENCES usuarios (id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_cancelacion_autoriza FOREIGN KEY (id_usuario_autoriza) REFERENCES usuarios (id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_cancelacion_motivo ON cancelaciones (id_motivo);
CREATE INDEX idx_cancelacion_fecha ON cancelaciones (fecha);
COMMENT ON COLUMN cancelaciones.comentario IS 'Obligatorio en la aplicación cuando el motivo es "Otro"';
COMMENT ON TABLE cancelaciones IS 'Autorización y motivo de la cancelación de una orden completa';
