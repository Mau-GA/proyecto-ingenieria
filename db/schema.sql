-- ---------------------------------------------------------------------
-- 9. BITÁCORA INALTERABLE
-- ---------------------------------------------------------------------
-- Registro forense de eventos relevantes. La cadena de hashes se calcula en
-- la base de datos: cada fila incluye el hash de la anterior y un SHA-256 de
-- los campos en un orden fijo (ver fn_bitacora_hash). Los triggers impiden
-- UPDATE, DELETE y TRUNCATE. El usuario dueño de la tabla podría desactivar
-- los triggers, pero la verificación de la cadena detecta cualquier cambio.
CREATE TABLE bitacora (
  id_bitacora     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_bitacora >= 0),
  fecha           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_usuario      INTEGER NULL,
  nombre_usuario  TEXT NULL,
  tipo_evento     TEXT NOT NULL CHECK (tipo_evento IN (
                    'LOGIN','LOGIN_FALLIDO','LOGOUT','PAGO','CANCELACION',
                    'AJUSTE_INVENTARIO','MERMA','COMPRA','CAMBIO_PRECIO','USUARIO')),
  entidad         TEXT NOT NULL,
  id_entidad      INTEGER NULL,
  datos_anteriores JSONB NULL,
  datos_nuevos    JSONB NULL,
  hash_anterior   CHAR(64) NULL,
  hash            CHAR(64) NOT NULL,
  PRIMARY KEY (id_bitacora),
  CONSTRAINT fk_bitacora_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX idx_bitacora_fecha ON bitacora (fecha);
CREATE INDEX idx_bitacora_tipo ON bitacora (tipo_evento);
CREATE INDEX idx_bitacora_usuario ON bitacora (id_usuario);
COMMENT ON COLUMN bitacora.nombre_usuario IS 'Copia del nombre de usuario al momento del evento; no depende de usuarios';
COMMENT ON COLUMN bitacora.hash_anterior IS 'Hash de la fila inmediatamente anterior en orden de id_bitacora';
COMMENT ON COLUMN bitacora.hash IS 'SHA-256 hexadecimal de hash_anterior + campos en orden fijo';
COMMENT ON TABLE bitacora IS 'Bitácora inalterable por triggers. Retención mínima: 1 año. No se purga.';

-- Calcula la cadena dentro de la misma transacción del evento. El advisory
-- lock fijo serializa las inserciones simultáneas para que dos filas no lean
-- el mismo "último hash" y rompan la cadena. Orden fijo documentado:
--   hash_anterior | id_bitacora | fecha (ISO con microsegundos) |
--   id_usuario | nombre_usuario | tipo_evento | entidad | id_entidad |
--   datos_anteriores::text | datos_nuevos::text
CREATE OR REPLACE FUNCTION fn_bitacora_hash() RETURNS trigger AS $$
DECLARE
  v_hash_anterior CHAR(64);
  v_texto TEXT;
BEGIN
  PERFORM pg_advisory_xact_lock(918273645);
  SELECT hash INTO v_hash_anterior
  FROM bitacora
  ORDER BY id_bitacora DESC
  LIMIT 1;

  NEW.hash_anterior := v_hash_anterior;
  v_texto :=
      COALESCE(v_hash_anterior, '') || '|' ||
      NEW.id_bitacora::text || '|' ||
      to_char(NEW.fecha, 'YYYY-MM-DD"T"HH24:MI:SS.US') || '|' ||
      COALESCE(NEW.id_usuario::text, '') || '|' ||
      COALESCE(NEW.nombre_usuario, '') || '|' ||
      NEW.tipo_evento || '|' ||
      NEW.entidad || '|' ||
      COALESCE(NEW.id_entidad::text, '') || '|' ||
      COALESCE(NEW.datos_anteriores::text, '') || '|' ||
      COALESCE(NEW.datos_nuevos::text, '');

  NEW.hash := encode(sha256(convert_to(v_texto, 'UTF8')), 'hex');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_bitacora_hash
BEFORE INSERT ON bitacora
FOR EACH ROW
EXECUTE FUNCTION fn_bitacora_hash();

-- El lock a nivel de sentencia se toma ANTES de que PostgreSQL evalúe los
-- valores por defecto de las filas. Así el id de identidad también se asigna
-- en el mismo orden en que se construye la cadena, incluso con inserciones
-- concurrentes. El lock del trigger por fila queda como respaldo para COPY o
-- inserciones que no disparen el trigger de sentencia.
CREATE OR REPLACE FUNCTION fn_bitacora_lock() RETURNS trigger AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(918273645);
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_bitacora_lock
BEFORE INSERT ON bitacora
FOR EACH STATEMENT
EXECUTE FUNCTION fn_bitacora_lock();

-- La bitácora es de solo lectura: ni UPDATE, ni DELETE, ni TRUNCATE.
CREATE OR REPLACE FUNCTION fn_bitacora_solo_lectura() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'La bitácora es de solo lectura';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_bitacora_update_delete
BEFORE UPDATE OR DELETE ON bitacora
FOR EACH ROW
EXECUTE FUNCTION fn_bitacora_solo_lectura();

CREATE TRIGGER trg_bitacora_truncate
BEFORE TRUNCATE ON bitacora
FOR EACH STATEMENT
EXECUTE FUNCTION fn_bitacora_solo_lectura();

