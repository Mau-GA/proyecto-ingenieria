COMMENT ON COLUMN tipos_movimiento_inventario.nombre IS 'Entrada por compra, Salida por venta, Merma, Ajuste, etc.';
COMMENT ON COLUMN tipos_movimiento_inventario.efecto IS 'Determina si suma o resta al stock_actual';

-- ---------------------------------------------------------------------
-- 3. PERSONAS: EMPLEADOS Y USUARIOS (separados a propósito)
-- ---------------------------------------------------------------------

CREATE TABLE empleados (
  id_empleado    INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_empleado >= 0),
  nombre         VARCHAR(60)  NOT NULL,
  apellido       VARCHAR(60)  NOT NULL,
  telefono       VARCHAR(20)  NULL,
  id_puesto      INTEGER NOT NULL,
  salario        DECIMAL(10,2) NULL CHECK (salario IS NULL OR salario >= 0),
  fecha_ingreso  DATE NOT NULL,
  fecha_baja     DATE NULL,
  estatus        CITEXT NOT NULL DEFAULT 'Activo' CHECK (estatus IN ('Activo','Inactivo','Baja')),
  creado_en      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_empleado),
  CONSTRAINT fk_empleado_puesto FOREIGN KEY (id_puesto) REFERENCES puestos (id_puesto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_empleado_fechas CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_ingreso)
);
CREATE INDEX idx_empleado_puesto ON empleados (id_puesto);

-- ON UPDATE CURRENT_TIMESTAMP de MariaDB -> trigger equivalente en PostgreSQL.
CREATE FUNCTION fn_empleados_actualizado_en() RETURNS trigger AS $$
BEGIN
  NEW.actualizado_en := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_empleados_actualizado_en
BEFORE UPDATE ON empleados
FOR EACH ROW
EXECUTE FUNCTION fn_empleados_actualizado_en();

-- Un usuario PUEDE (no debe) estar ligado a un empleado: permite cuentas de
-- acceso administrativas sin ficha laboral, y empleados sin cuenta.
CREATE TABLE usuarios (
  id_usuario     INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY CHECK (id_usuario >= 0),
  id_empleado    INTEGER NULL,
  nombre_usuario CITEXT   NOT NULL,
  correo         CITEXT   NULL,
  password_hash  VARCHAR(255) NOT NULL,
  activo         BOOLEAN  NOT NULL DEFAULT TRUE,
  ultimo_acceso  TIMESTAMP NULL,
  creado_en      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuario_nombre   UNIQUE (nombre_usuario),
  CONSTRAINT uq_usuario_correo   UNIQUE (correo),
  CONSTRAINT uq_usuario_empleado UNIQUE (id_empleado),
  CONSTRAINT fk_usuario_empleado FOREIGN KEY (id_empleado) REFERENCES empleados (id_empleado) ON DELETE SET NULL ON UPDATE CASCADE
);
COMMENT ON COLUMN usuarios.password_hash IS 'Hash bcrypt/argon2 generado en el backend. Nunca texto plano.';

CREATE TABLE usuarios_roles (
  id_usuario INTEGER NOT NULL,
  id_rol     INTEGER NOT NULL,
  PRIMARY KEY (id_usuario, id_rol),
  CONSTRAINT fk_ur_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_ur_rol     FOREIGN KEY (id_rol)     REFERENCES roles (id_rol)       ON DELETE CASCADE ON UPDATE CASCADE
);

